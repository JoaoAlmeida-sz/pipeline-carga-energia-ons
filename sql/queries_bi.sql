-- Evolução diária do SIN: soma dos quatro subsistemas no mesmo dia.
SELECT
    d.DATA,
    SUM(f.CARGA_MWMED) AS CARGA_SIN_MWMED
FROM ONS_ENERGIA.ANALYTICS.FCT_CARGA_DIARIA f
JOIN ONS_ENERGIA.ANALYTICS.DIM_DATA d ON f.DATA_KEY = d.DATA_KEY
GROUP BY d.DATA
ORDER BY d.DATA;

-- Comparação mensal por subsistema: usar a média diária em MWmed.
SELECT
    INICIO_MES,
    SUBSISTEMA,
    DIAS_OBSERVADOS,
    CARGA_MEDIA_MWMED
FROM ONS_ENERGIA.ANALYTICS.MART_CARGA_MENSAL
ORDER BY INICIO_MES, SUBSISTEMA;

