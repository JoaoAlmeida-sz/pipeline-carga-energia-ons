-- Execute uma vez com ACCOUNTADMIN, depois de criar os objetos em bootstrap.sql.
-- Esta role acessa apenas o banco e o warehouse deste projeto.
USE ROLE ACCOUNTADMIN;
-- O usuário desta conta usa identificador em minúsculas; preservar a caixa.
SET pipeline_user = '"' || CURRENT_USER() || '"';

CREATE ROLE IF NOT EXISTS ONS_PIPELINE_ROLE;
GRANT USAGE ON WAREHOUSE ONS_WH TO ROLE ONS_PIPELINE_ROLE;
GRANT USAGE ON DATABASE ONS_ENERGIA TO ROLE ONS_PIPELINE_ROLE;
GRANT USAGE ON SCHEMA ONS_ENERGIA.RAW TO ROLE ONS_PIPELINE_ROLE;
GRANT USAGE ON SCHEMA ONS_ENERGIA.ANALYTICS TO ROLE ONS_PIPELINE_ROLE;
GRANT CREATE TABLE ON SCHEMA ONS_ENERGIA.RAW TO ROLE ONS_PIPELINE_ROLE;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA ONS_ENERGIA.ANALYTICS TO ROLE ONS_PIPELINE_ROLE;

-- Os objetos da carga inicial foram criados com ACCOUNTADMIN. O dbt precisa
-- ser dono dos modelos existentes para poder substituí-los em cada execução.
GRANT OWNERSHIP ON TABLE ONS_ENERGIA.RAW.CARGA_ENERGIA_DIARIA
  TO ROLE ONS_PIPELINE_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL TABLES IN SCHEMA ONS_ENERGIA.ANALYTICS
  TO ROLE ONS_PIPELINE_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL VIEWS IN SCHEMA ONS_ENERGIA.ANALYTICS
  TO ROLE ONS_PIPELINE_ROLE COPY CURRENT GRANTS;
GRANT ROLE ONS_PIPELINE_ROLE TO USER IDENTIFIER($pipeline_user);

-- O GitHub Actions usa IPs variáveis. Sem política de rede nesta conta, o PAT
-- só autentica com uma exceção por usuário. Ela mantém qualquer política de
-- rede futura, exige role restrita e limita o vencimento do token a 90 dias.
CREATE AUTHENTICATION POLICY IF NOT EXISTS ONS_ENERGIA.RAW.ONS_PIPELINE_PAT_POLICY
  PAT_POLICY = (
    DEFAULT_EXPIRY_IN_DAYS = 30
    MAX_EXPIRY_IN_DAYS = 90
    NETWORK_POLICY_EVALUATION = ENFORCED_NOT_REQUIRED
    REQUIRE_ROLE_RESTRICTION_FOR_PERSON_USERS = TRUE
    BLOCKED_ROLES_LIST = ('ACCOUNTADMIN', 'SYSADMIN')
  );
ALTER USER IDENTIFIER($pipeline_user)
  SET AUTHENTICATION POLICY ONS_ENERGIA.RAW.ONS_PIPELINE_PAT_POLICY;
