  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS ONS_ENERGIA;
CREATE SCHEMA IF NOT EXISTS ONS_ENERGIA.RAW;
CREATE SCHEMA IF NOT EXISTS ONS_ENERGIA.ANALYTICS;

